// Builds CSS variables and a typed token map from tokens/figma-variables.json.
// Run: npm run tokens
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(readFileSync(join(root, 'tokens/figma-variables.json'), 'utf8'));
const C = src.collections;

const PREFIX = '--ds-';
const slug = (s) =>
  s.toLowerCase().replace(/·/g, ' ').replace(/(\d+)%/g, 'a$1').replace(/'/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// How each Figma collection maps to CSS: variable naming, mode attribute, default mode.
const FONT_WEIGHTS = { Regular: 400, Medium: 500, 'Semi Bold': 600, Bold: 700, Black: 900 };
const FONT_STACKS = {
  "Suisse Int'l": `"Suisse Int'l", "Helvetica Neue", Helvetica, system-ui, sans-serif`,
  Consolas: `Consolas, ui-monospace, "SFMono-Regular", Menlo, monospace`,
};
const COMPONENT_KEYS = {
  Height: 'height', 'Horizontal Padding': 'padding-x', 'Vertical Padding': 'padding-y', 'Horizontal Gap': 'gap',
  'Font Size': 'font-size', 'Line Height': 'line-height', 'Font Weight': 'font-weight', 'Icon Size': 'icon-size',
  Radius: 'radius', 'Corner Radius': 'radius', 'Row Height': 'row-height', 'Header Height': 'header-height', Gap: 'gap',
};
const RULES = {
  Colors: { name: (n) => (n === 'White/White' ? 'color-white' : 'color-' + slug(n)) },
  Tokens: { name: (n) => slug(n) },
  Size: {
    name: (n) => {
      const [group, key] = n.split('/');
      const g = { Space: 'space', Radius: 'radius', Stroke: 'stroke-width', 'Font Size': 'font-size', 'Line Height': 'line-height' }[group];
      return `${g}-${slug(key)}`;
    },
  },
  Typography: { name: (n) => (n.startsWith('Weight/') ? 'font-weight-' : 'font-family-') + slug(n.split('/')[1]) },
  Context: { name: (n) => 'context-' + slug(n), attr: 'data-context', default: 'Brand' },
  Appearance: { name: (n) => 'appearance-' + (n === 'Stroke Value' ? 'stroke-width' : slug(n)), attr: 'data-appearance', default: 'Fill' },
  'Size [Button]': { name: (n) => 'button-' + COMPONENT_KEYS[n], attr: 'data-button-size', default: 'm' },
  'Size [Input]': { name: (n) => 'input-' + COMPONENT_KEYS[n], attr: 'data-input-size', default: 'm' },
  'Size [Table]': { name: (n) => 'table-' + COMPONENT_KEYS[n], attr: 'data-table-density', default: 'Default' },
  'Size [Badge]': { name: (n) => 'badge-' + COMPONENT_KEYS[n], attr: 'data-badge-size', default: 's' },
  'Shape [Badge]': { name: (n) => 'badge-' + COMPONENT_KEYS[n], attr: 'data-badge-shape', default: 'Rounded' },
};
const modeSlug = (m) => slug(m.replace(/\(.*\)/, ''));

// Index every variable by "Collection:Name".
const index = new Map();
for (const [cName, col] of Object.entries(C)) {
  const rule = RULES[cName];
  if (!rule) throw new Error(`No mapping rule for collection "${cName}"`);
  for (const [name, type, value, description] of col.vars) {
    const values = col.modes.length === 1 ? [value] : value;
    if (values.length !== col.modes.length) throw new Error(`${cName}:${name} has ${values.length} values for ${col.modes.length} modes`);
    index.set(`${cName}:${name}`, { collection: cName, name, type, values, description: description ?? '', cssVar: PREFIX + rule.name(name) });
  }
}
const cssNames = new Map();
for (const t of index.values()) {
  if (cssNames.has(t.cssVar)) throw new Error(`CSS name clash: ${t.cssVar} (${cssNames.get(t.cssVar)} and ${t.collection}:${t.name})`);
  cssNames.set(t.cssVar, `${t.collection}:${t.name}`);
}

const isAlias = (v) => typeof v === 'string' && v.startsWith('@');
const target = (v) => {
  const t = index.get(v.slice(1));
  if (!t) throw new Error(`Unresolved alias ${v}`);
  return t;
};
// Resolve a value to its raw value, following aliases. Moded targets resolve in their default mode
// unless the caller passes the mode chosen for that collection.
function resolve(v, modes = {}) {
  if (!isAlias(v)) return v;
  const t = target(v);
  const col = C[t.collection];
  const m = modes[t.collection] ?? RULES[t.collection].default ?? col.modes[0];
  return resolve(t.values[col.modes.indexOf(m)], modes);
}
function cssValue(t, v) {
  if (isAlias(v)) return `var(${target(v).cssVar})`;
  if (t.type === 'F') return v === 0 ? '0' : `${v}px`;
  if (t.type === 'S' && t.name.startsWith('Weight/')) return String(FONT_WEIGHTS[v]);
  if (t.type === 'S' && t.name.startsWith('Family/')) return FONT_STACKS[v] ?? `"${v}", sans-serif`;
  return v;
}

// ---------- CSS ----------
const out = [];
out.push(`/* Generated by scripts/build-tokens.mjs from tokens/figma-variables.json (Figma file ${src.meta.figmaFileKey}, exported ${src.meta.exportedAt}). Do not edit by hand. */`);
const decl = (t, v) => `  ${t.cssVar}: ${cssValue(t, v)};`;
const ofCollection = (c) => [...index.values()].filter((t) => t.collection === c);

out.push('', ':root {');
for (const c of ['Colors', 'Tokens', 'Size', 'Typography']) {
  out.push(`  /* ${c} */`);
  for (const t of ofCollection(c)) out.push(decl(t, t.values[0]));
}
out.push('}');

for (const c of ['Context', 'Appearance', 'Size [Button]', 'Size [Input]', 'Size [Table]', 'Size [Badge]', 'Shape [Badge]']) {
  const col = C[c];
  const rule = RULES[c];
  out.push('', `/* ${c}: modes ${col.modes.join(', ')}. Set ${rule.attr}="${col.modes.map(modeSlug).join('|')}"; default ${rule.default}. */`);
  col.modes.forEach((m, i) => {
    const own = `[${rule.attr}="${modeSlug(m)}"]`;
    const sel = [own];
    if (m === rule.default) sel.unshift(':root');
    // Appearance reads Context variables, which CSS resolves where they are declared. Re-declare the
    // appearance on any element that changes context without setting its own appearance.
    if (c === 'Appearance') {
      if (m === rule.default) sel.push('[data-context]:not([data-appearance])');
    }
    out.push(`${sel.join(',\n')} {`);
    for (const t of ofCollection(c)) out.push(decl(t, t.values[i]));
    out.push('}');
  });
  if (c === 'Appearance') {
    // Inside an appearance scope, a nested context change keeps that scope's appearance.
    col.modes.forEach((m, i) => {
      out.push(`:where([data-appearance="${modeSlug(m)}"]) [data-context]:not([data-appearance]) {`);
      for (const t of ofCollection(c)) out.push(decl(t, t.values[i]));
      out.push('}');
    });
  }
}
mkdirSync(join(root, 'src/tokens'), { recursive: true });
writeFileSync(join(root, 'src/tokens/tokens.css'), out.join('\n') + '\n');

// ---------- TypeScript ----------
const collections = Object.entries(C).map(([cName, col]) => {
  const rule = RULES[cName];
  return {
    name: cName,
    modes: col.modes,
    modeAttribute: rule.attr ?? null,
    modeValues: rule.attr ? col.modes.map(modeSlug) : null,
    defaultMode: rule.default ?? col.modes[0],
    tokens: ofCollection(cName).map((t) => ({
      name: t.name,
      type: t.type === 'C' ? 'color' : t.type === 'F' ? 'dimension' : 'string',
      cssVar: t.cssVar,
      description: t.description,
      byMode: Object.fromEntries(
        col.modes.map((m, i) => {
          const v = t.values[i];
          return [m, { alias: isAlias(v) ? v.slice(1) : null, value: resolve(v, { [cName]: m }) }];
        }),
      ),
    })),
  };
});
const ts = `// Generated by scripts/build-tokens.mjs. Do not edit by hand.
export type TokenType = 'color' | 'dimension' | 'string';
export interface TokenModeValue { alias: string | null; value: string | number }
export interface Token { name: string; type: TokenType; cssVar: string; description: string; byMode: Record<string, TokenModeValue> }
export interface TokenCollection { name: string; modes: string[]; modeAttribute: string | null; modeValues: string[] | null; defaultMode: string; tokens: Token[] }

export const source = ${JSON.stringify(src.meta, null, 2)} as const;

export const collections: TokenCollection[] = ${JSON.stringify(collections, null, 2)};

export const collection = (name: string): TokenCollection => {
  const c = collections.find((x) => x.name === name);
  if (!c) throw new Error('Unknown collection ' + name);
  return c;
};
`;
writeFileSync(join(root, 'src/tokens/tokens.ts'), ts);

const count = [...index.values()].length;
console.log(`tokens: ${count} variables from ${Object.keys(C).length} collections -> src/tokens/tokens.css, src/tokens/tokens.ts`);
